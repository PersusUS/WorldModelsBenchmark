FAMILY_LABEL = {"minigrid": "MiniGrid", "gymnasium": "Gymnasium",
                "dmcontrol": "DMControl"}
LEVEL_LABEL = {"distance_min": "min", "distance_med": "med",
               "distance_max": "max"}
METHOD_LABEL = {
    "finetuning": "Fine-tuning",
    "replay_infinite": "Replay",
    "ewc": "EWC",
    "progressive_nets": "Prog.\\ Nets",
    "ug_mtm": "UG-MTM",
}
HEADER = ("% Generated by experiments/export_tables.py -- do not edit by hand.\n"
          "% Regenerate after any change to results/ or to the aggregation.\n")

# Table 1 of the paper: a label and a number format per protocol field, in
# reading order rather than the config's. The keys are checked against the
# runner's own field lists at import, so a field the runner starts recording
# cannot go missing from Table 1 in silence.
PROTOCOL_ROWS = [
    ("n_collect", "Episodes collected per task (random policy)"),
    ("n_train", "Gradient updates per task"),
    ("batch_size", "Batch size"),
    ("seq_len", "Sequence length"),
    ("learning_rate", "Learning rate (Adam)", "{:.0e}"),
    ("latent_dim", "Latent dimension"),
    ("hidden_dim", "GRU hidden dimension"),
    ("beta_kl", "KL weight $\\beta$", "{:.1f}"),
    ("n_eval_episodes", "Held-out task-A episodes"),
    ("n_eval_transitions", "Transitions in $D_A$"),
    ("n_recon_frames", "Held-out frames for pixel reconstruction"),
    ("rd_horizon", "RD rollout horizon"),
    ("rd_samples", "RD start states"),
    ("n_fisher_transitions", "Transitions in EWC's Fisher estimate"),
    ("ewc_lambda", "EWC $\\lambda$"),
    ("mc_dropout_T_train", "UG-MTM MC-dropout samples (training)"),
]
# Recorded by the runner and deliberately not in Table 1: a plotting detail,
# the weights of an aggregate the paper withdrew (D10), and the seed list,
# which gets its own row. Named rather than merely absent, so the check below
# can tell a decision from an oversight.
PROTOCOL_OMITTED = {"curve_points", "wmf_weights", "seeds"}

# How each entry of the physics vector is rendered, and the value at which it
# is no perturbation and so not worth printing (gravity has none). The keys are
# `PHYSICS_PARAMS`, which is what Eq. 8 differences: a wrapper parameter that
# enters the distance has to enter the label with it or the task table
# under-reports a perturbation the distance scored.
PARAM_ROWS = [
    ("gravity", "$g={:g}$", None),
    ("mass_scale", r"mass $\times{:g}$", 1.0),
    ("friction_scale", r"friction $\times{:g}$", 1.0),
]


def _check_the_labels_cover_the_fields():
    recorded = set(PROTOCOL_FIELDS) | set(MODEL_FIELDS) | {"seeds"}
    unlabelled = recorded - {row[0] for row in PROTOCOL_ROWS} - PROTOCOL_OMITTED
    if unlabelled:
        raise ValueError(
            f"protocol field(s) {sorted(unlabelled)} have no label: add them "
            "to PROTOCOL_ROWS or to PROTOCOL_OMITTED, so Table 1 either "
            "describes the whole protocol or says on purpose that it does not."
        )
    labelled = {row[0] for row in PARAM_ROWS}
    if labelled != set(PHYSICS_PARAMS):
        raise ValueError(
            "PARAM_ROWS and distances.PHYSICS_PARAMS disagree on the physics "
            f"vector: {sorted(labelled ^ set(PHYSICS_PARAMS))}"
        )


_check_the_labels_cover_the_fields()


def fmt(value, digits=2):
    """A number, or an en-dash when the cell has no data."""
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return "--"
    return f"{value:.{digits}f}"


def latex_escape(text):
    """dm_control names underscores (`point_mass`, `ball_in_cup`); LaTeX does
    not. Only the characters that can reach us from an environment id."""
    return text.replace("_", r"\_")


def family_cell(lines, family, previous):
    """
    The family column of a grouped table: the name on the first row of its
    block, blank after that, with a rule between blocks.

    Appends to `lines` in place and returns the label. Four tables group by
    family, and they have to group identically or the paper's tables stop
    looking like each other.
    """
    if previous is not None and family != previous:
        lines.append(r"\addlinespace")
    return FAMILY_LABEL.get(family, family) if family != previous else ""


def protocol_table(runs):
    """
    The executed protocol, read off the runs rather than off the config.

    Every metrics.json stores the protocol block it was produced under.
    Building Table 1 from those blocks is what keeps the paper's protocol and
    the executed one from drifting apart, which is exactly how the previous
    version came to describe a budget it never ran.

    Disagreement is `check_runs_consistent`'s job, not this one's; by the time
    a table is being built the directory has already been vetted.
    """
    protocol = shared_protocol([r for r in runs if r.get("protocol")])
    if protocol is None:
        raise ValueError("no run carries a protocol block")

    lines = [HEADER, r"\begin{tabular}{lr}", r"\toprule",
             r"Parameter & Value \\", r"\midrule"]
    for key, label, *spec in PROTOCOL_ROWS:
        if key in protocol:
            number = (spec[0] if spec else "{:.0f}").format(
                float(protocol[key]))
            lines.append(f"{label} & {number} \\\\")
    # Seeds are counted off the runs, never read from the protocol block: once
    # seeds are added to a finished grid the block records what an invocation
    # was asked for, and only the cells know what exists. They need not be
    # equal across cells, so this reports the range and Table 2 the detail.
    counts = seed_counts(runs)
    lines.append("Seeds per cell & "
                 + (f"{counts[0]}" if len(counts) == 1
                    else f"{counts[0]}--{counts[-1]}")
                 + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def task_label(spec):
    """`env_id`, or dm_control's `domain/task`, plus the physics it was given.

    The Gym/MiniGrid boilerplate is dropped: every id in the table carries the
    same `MiniGrid-` prefix and `-v0` suffix, and with them the widest row runs
    to 138 characters, which overflows the text width of a one-column article
    even at \\small. The family column already says which suite it is.
    """
    name = spec.get("env_id") or \
        f"{spec.get('domain_name')}/{spec.get('task_name')}"
    for prefix in ("MiniGrid-",):
        name = name[len(prefix):] if name.startswith(prefix) else name
    for suffix in ("-v0", "-v4", "-v5"):
        name = name[:-len(suffix)] if name.endswith(suffix) else name
    text = r"\texttt{" + latex_escape(name) + "}"
    params = spec.get("params") or {}
    parts = [label.format(params[key]) for key, label, neutral in PARAM_ROWS
             if key in params and params[key] != neutral]
    if parts:
        text += " (" + ", ".join(parts) + ")"
    return text


def tasks_table(runs, families, distances):
    """
    The nine cells: which two environments each one trains on, in that order.

    Read from each run's `tasks` block for the same reason as the protocol —
    the levels were edited three times (F8, F25, F26) and the config is not
    evidence of what produced the numbers. That a cell's runs agree on their
    pair is `check_runs_consistent`'s job.
    """
    seeds_by_cell = observed_seeds(runs)
    lines = [HEADER, r"\begin{tabular}{llllrrr}", r"\toprule",
             r"Family & Level & Task A & Task B & Seeds & "
             r"$d_{\mathrm{param}}$ & $d_{\mathrm{trans}}$ \\",
             r"\midrule"]
    previous = None
    for family in families:
        for distance in distances:
            tasks = cell_tasks(runs, family, distance)
            if tasks is None:
                continue
            per_seed = list(cell_d_trans(runs, family, distance).values())
            name = family_cell(lines, family, previous)
            previous = family
            lines.append(
                f"{name} & {LEVEL_LABEL[distance]} & "
                f"{task_label(tasks['task_A'])} & "
                f"{task_label(tasks['task_B'])} & "
                + str(len(seeds_by_cell.get((family, distance), []))) + " & "
                + fmt(d_param_for_pair(tasks), 3) + " & "
                + (fmt(float(np.median(per_seed))) if per_seed else "--")
                + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def median_of(runs, method, family, distance, key):
    values = list(cell_values(runs, method, family, distance, key).values())
    return float(np.median(values)) if values else float("nan")


def axis_table(runs, families, distances, axis_methods, key="rd"):
    """RD per family and level, with the level it peaks at (F27)."""
    lines = [HEADER, r"\begin{tabular}{lrrrc}", r"\toprule",
             r"Family & min & med & max & Peak \\", r"\midrule"]
    for family in families:
        values = [axis_value(runs, axis_methods, family, d, key)
                  for d in distances]
        if all(np.isnan(v) for v in values):
            continue
        peak = LEVEL_LABEL[distances[int(np.nanargmax(values))]]
        cells = " & ".join(
            (r"\textbf{" + fmt(v) + "}" if LEVEL_LABEL[distances[i]] == peak
             else fmt(v))
            for i, v in enumerate(values))
        lines.append(f"{FAMILY_LABEL.get(family, family)} & {cells} & "
                     f"{peak} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def predictor_table(runs, families, distances, axis_methods, key="rd"):
    """The nine cells behind the rank correlations, and the correlations."""
    cells, observed, labels, d_trans, difficulty = [], [], [], [], []
    for family in families:
        for distance in distances:
            value = axis_value(runs, axis_methods, family, distance, key)
            if np.isnan(value):
                continue
            cells.append((family, distance))
            observed.append(value)
            labels.append(distances.index(distance))
            per_seed = list(cell_d_trans(runs, family, distance).values())
            d_trans.append(float(np.median(per_seed)) if per_seed
                           else float("nan"))
            difficulty.append(axis_value(
                runs, axis_methods, family, distance,
                "heldout_reconstruction_B_after_task_B"))

    lines = [HEADER, r"\begin{tabular}{llrrr}", r"\toprule",
             r"Family & Level & RD & $d_{\mathrm{trans}}$ & "
             r"Task-B difficulty \\", r"\midrule"]
    previous = None
    for (family, distance), obs, dt, diff in zip(cells, observed, d_trans,
                                                 difficulty):
        name = family_cell(lines, family, previous)
        previous = family
        lines.append(f"{name} & {LEVEL_LABEL[distance]} & {fmt(obs)} & "
                     f"{fmt(dt)} & {fmt(diff)} \\\\")
    lines.append(r"\midrule")
    lines.append(r"\multicolumn{2}{l}{Spearman $\rho$ with RD} & "
                 + " & ".join([
                     fmt(spearman(observed, labels)),
                     fmt(spearman(observed, d_trans)),
                     fmt(spearman(observed, difficulty)),
                 ]) + r" \\")
    lines.append(r"\multicolumn{2}{l}{\quad (predictor)} & "
                 r"\emph{labelled level} & \emph{measured} & \emph{measured}"
                 r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def encoder_table(runs, methods, families, distances, threshold=0.10):
    """
    Task-A reconstruction after task B, as a factor of what it was before.

    A factor rather than the percentage the console prints: the column has to
    hold 1.00 and 753 in the same table, and "+75244.5\\%" is unreadable next
    to "+0.0\\%". They are the same quantity, factor = 1 + loss.
    """
    controls = control_cells(runs, methods, families, distances, threshold)
    header = " & ".join(METHOD_LABEL.get(m, m) for m in methods)
    lines = [HEADER,
             r"\begin{tabular}{ll" + "r" * len(methods) + "}", r"\toprule",
             f"Family & Level & {header} \\\\", r"\midrule"]
    previous = None
    for family in families:
        for distance in distances:
            losses = [task_a_loss(runs, m, family, distance) for m in methods]
            if all(np.isnan(x) for x in losses):
                continue
            name = family_cell(lines, family, previous)
            previous = family
            level = LEVEL_LABEL[distance]
            if (family, distance) in controls:
                level += r"$^{\dagger}$"
            cells = " & ".join(
                "--" if np.isnan(x) else
                (f"{1 + x:.2f}" if abs(x) < 10 else f"{1 + x:.0f}")
                for x in losses)
            lines.append(f"{name} & {level} & {cells} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def method_table(runs, methods, families, distances, key):
    """Median over seeds of `key`, per method and cell, marking skewed cells."""
    header = " & ".join(METHOD_LABEL.get(m, m) for m in methods)
    lines = [HEADER,
             r"\begin{tabular}{ll" + "r" * len(methods) + "}", r"\toprule",
             f"Family & Level & {header} \\\\", r"\midrule"]
    previous = None
    for family in families:
        for distance in distances:
            cells = []
            for method in methods:
                values = list(cell_values(runs, method, family, distance,
                                          key).values())
                if not values:
                    cells.append("--")
                    continue
                median = float(np.median(values))
                text = f"{median:.2f}" if abs(median) < 100 else f"{median:.0f}"
                if is_right_skewed(values):
                    text += r"$^{\ast}$"
                cells.append(text)
            if all(c == "--" for c in cells):
                continue
            name = family_cell(lines, family, previous)
            previous = family
            lines.append(f"{name} & {LEVEL_LABEL[distance]} & "
                         + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def quality_table(runs, methods, families, distances):
    """
    Was there anything to forget? Task-A quality per cell, before any switch.

    A forgetting benchmark has to establish this before any of its numbers mean
    anything: if the model never learned task A, PF and RD are the distance
    between two bad models. Pooled over methods, because at this point in the
    protocol every method has trained on task A and nothing else.
    """
    lines = [HEADER, r"\begin{tabular}{llrrr}", r"\toprule",
             r"Family & Level & Held-out recon. & NLL at init & NLL after A \\",
             r"\midrule"]
    previous = None
    for family in families:
        for distance in distances:
            recon, at_init, after = [], [], []
            for method in methods:
                recon += list(cell_values(
                    runs, method, family, distance,
                    "heldout_reconstruction_A_after_task_A").values())
                at_init += list(cell_values(runs, method, family, distance,
                                            "nll_A_random_init").values())
                after += list(cell_values(runs, method, family, distance,
                                          "nll_A_after_task_A").values())
            if not recon:
                continue
            name = family_cell(lines, family, previous)
            previous = family
            lines.append(
                f"{name} & {LEVEL_LABEL[distance]} & "
                + fmt(float(np.median(recon))) + " & "
                + (fmt(float(np.median(at_init))) if at_init else "--") + " & "
                + (fmt(float(np.median(after))) if after else "--") + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def sequence_table(runs, methods, task=0):
    """
    Retention of one task as a sequence of k tasks goes on (D22/R20).

    Two columns of the paired grid's story in one table: the latent scale that
    PF and RD live on, and the pixel factor they cannot see. The peak column
    counts seeds rather than reading the median curve -- a peak that only
    survives averaging is a property of the average.
    """
    k = runs[0]["k"]
    stages = list(range(task + 1, k))
    header = " & ".join(f"after $T_{s + 1}$" for s in stages)
    # A single header row rather than a stacked one: the alternative needs
    # \multirow, and a generated table should not add a package to the
    # preamble of a document it does not own.
    lines = [HEADER,
             r"\begin{tabular}{l" + "r" * len(stages) + "cr}", r"\toprule",
             f"Method & {header} & Peak & Pixel $\\times$ \\\\", r"\midrule"]
    for method in methods:
        curve = retention_curve(runs, method, task, "rd")
        if not curve:
            continue
        peak, agreeing, n_seeds = peak_stage(runs, method, task)
        cells = []
        for stage in stages:
            text = fmt(float(np.median(curve[stage]))) if stage in curve else "--"
            if stage == peak:
                text = r"\textbf{" + text + "}"
            cells.append(text)
        final = encoder_factor(runs, method, task, stages[-1])
        cells.append(f"$T_{peak + 1}$ ({agreeing}/{n_seeds})")
        # Rendered like the paired grid's encoder table, and for the same
        # reason: 1.00 and 773 share a column, and it lets the prose quote the
        # table verbatim instead of rounding it a second time.
        if not final:
            cells.append("--")
        else:
            factor = float(np.median(final))
            cells.append(f"{factor:.2f}" if factor < 10 else f"{factor:.0f}")
        lines.append(f"{METHOD_LABEL.get(method, method)} & "
                     + " & ".join(cells) + r" \\")
    lines.append(r"\midrule")
    # The difficulty of the task each stage trains on, which is what the peak
    # tracks. Pooled over methods: at that moment each has just trained on it.
    difficulty = " & ".join(
        fmt(float(np.median(task_difficulty(runs, s)))) for s in stages)
    lines.append("Difficulty of the task trained there & " + difficulty
                 + r" & & \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--results-dir", default="results", type=Path)
    parser.add_argument("--sequence-dir", default=Path("results-seq"), type=Path,
                        help="k>2 runs; the sequence table is skipped if absent")
    parser.add_argument("--out", default=Path("../paper/tables"), type=Path)
    parser.add_argument("--methods", nargs="+", default=METHODS)
    parser.add_argument("--families", nargs="+", default=list(FAMILY_CONFIGS))
    parser.add_argument("--distances", nargs="+", default=DISTANCES)
    parser.add_argument("--axis-methods", nargs="+", default=AXIS_METHODS)
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    runs = load_runs(args.results_dir)
    if not runs:
        raise SystemExit(f"no metrics.json found under {args.results_dir}")
    # Once, here, rather than in each table: every table below medians over
    # cells, and a cell that mixes two budgets or two task pairs would be
    # averaged in silence by all eight of them.
    check_runs_consistent(runs)

    present = {(r.get("method"), r.get("family"), r.get("distance"))
               for r in runs}
    methods = [m for m in args.methods if any(p[0] == m for p in present)]
    families = [f for f in args.families if any(p[1] == f for p in present)]
    distances = [d for d in args.distances if any(p[2] == d for p in present)]
    axis_methods = [m for m in args.axis_methods if m in methods]

    tables = {
        "protocol": protocol_table(runs),
        "tasks": tasks_table(runs, families, distances),
        "axis": axis_table(runs, families, distances, axis_methods),
        "predictors": predictor_table(runs, families, distances, axis_methods),
        "encoder": encoder_table(runs, methods, families, distances),
        "pf": method_table(runs, methods, families, distances, "pf"),
        "rd": method_table(runs, methods, families, distances, "rd"),
        "ft": method_table(runs, methods, families, distances, "ft"),
        "quality": quality_table(runs, methods, families, distances),
    }

    # Optional: the k>2 runs live in their own directory under their own
    # schema, and the paper's k=2 tables do not depend on them existing.
    sequence_runs = load_sequence_runs(args.sequence_dir)
    if sequence_runs:
        check_sequence_runs(sequence_runs)
        present = [m for m in args.methods
                   if any(r.get("method") == m for r in sequence_runs)]
        tables["sequence"] = sequence_table(sequence_runs, present)
    else:
        print(f"no sequence runs under {args.sequence_dir}: skipping tab_sequence")

    args.out.mkdir(parents=True, exist_ok=True)
    for name, body in tables.items():
        path = args.out / f"tab_{name}.tex"
        path.write_text(body, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
