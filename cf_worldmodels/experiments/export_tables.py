"""
Emit the paper's result tables as LaTeX, from the stored metrics.json files.

Same rule as `summarize_results.py`, and the same reason: a table that is
transcribed by hand drifts from the runs it claims to describe. Everything here
is computed by importing that module, so the paper and the console summary can
disagree only if the code disagrees with itself.

Each table is written as a bare `tabular` with no caption or label, so the
section file can wrap it in whatever float it wants:

    python experiments/export_tables.py --out ../paper/tables

Requires `booktabs` in the document preamble.
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent.parent))

from experiments.run_full_benchmark import DISTANCES, FAMILY_CONFIGS, METHODS
from src.benchmark.distances import compute_d_param
from experiments.summarize_results import (
    AXIS_METHODS,
    axis_value,
    cell_values,
    control_cells,
    load_runs,
    is_right_skewed,
    spearman,
    task_a_loss,
)

FAMILY_LABEL = {"minigrid": "MiniGrid", "gymnasium": "Gymnasium",
                "dmcontrol": "DMControl"}
LEVEL_LABEL = {"distance_min": "min", "distance_med": "med",
               "distance_max": "max"}
METHOD_LABEL = {
    "finetuning": "Fine-tuning",
    "replay_infinite": "Replay",
    "ewc": "EWC",
    "progressive_nets": "Prog.\\ Nets",
    "ug_mtm": "UG-MTM",
}
HEADER = ("% Generated by experiments/export_tables.py -- do not edit by hand.\n"
          "% Regenerate after any change to results/ or to the aggregation.\n")

# Table 1 of the paper. The order is the reading order, not the config's, and
# the labels are what the paper calls these quantities; the values come from
# the runs. Fields the runner records but that describe nothing a reader needs
# (curve_points, the WMF weights of a withdrawn aggregate) are left out.
PROTOCOL_ROWS = [
    ("n_collect", "Episodes collected per task (random policy)", "{:.0f}"),
    ("n_train", "Gradient updates per task", "{:.0f}"),
    ("batch_size", "Batch size", "{:.0f}"),
    ("seq_len", "Sequence length", "{:.0f}"),
    ("learning_rate", "Learning rate (Adam)", "{:.0e}"),
    ("latent_dim", "Latent dimension", "{:.0f}"),
    ("hidden_dim", "GRU hidden dimension", "{:.0f}"),
    ("beta_kl", "KL weight $\\beta$", "{:.1f}"),
    ("n_eval_episodes", "Held-out task-A episodes", "{:.0f}"),
    ("n_eval_transitions", "Transitions in $D_A$", "{:.0f}"),
    ("n_recon_frames", "Held-out frames for pixel reconstruction", "{:.0f}"),
    ("rd_horizon", "RD rollout horizon", "{:.0f}"),
    ("rd_samples", "RD start states", "{:.0f}"),
    ("n_fisher_transitions", "Transitions in EWC's Fisher estimate", "{:.0f}"),
    ("ewc_lambda", "EWC $\\lambda$", "{:.0f}"),
    ("mc_dropout_T_train", "UG-MTM MC-dropout samples (training)", "{:.0f}"),
]

# Physics keys the environment wrappers implement, with the value that means
# "unperturbed". A scale of 1 is not a perturbation and is dropped from the
# label; gravity has no neutral value, so it is shown whenever it is declared.
PARAM_ROWS = [
    ("gravity", "$g={:g}$", None),
    ("mass_scale", r"mass $\times{:g}$", 1.0),
    ("friction_scale", r"friction $\times{:g}$", 1.0),
]


def fmt(value, digits=2):
    """A number, or an en-dash when the cell has no data."""
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return "--"
    return f"{value:.{digits}f}"


def latex_escape(text):
    return str(text).replace("_", r"\_").replace("&", r"\&")


def protocol_table(runs):
    """
    The executed protocol, read off the runs rather than off the config.

    Every metrics.json stores the protocol block it was produced under, and
    the runner refuses to write two budgets into one cell. Building Table 1
    from those blocks is what keeps the paper's protocol and the executed one
    from drifting apart, which is exactly how the previous version came to
    describe a budget it never ran. If the loaded runs disagree, that is a
    fact about the results directory and this raises rather than picking one.
    """
    protocols = {}
    for entry in runs:
        protocol = entry.get("protocol")
        if not protocol:
            continue
        key = tuple(sorted((k, str(v)) for k, v in protocol.items()))
        protocols.setdefault(key, protocol)
    if not protocols:
        raise ValueError("no run carries a protocol block")
    if len(protocols) > 1:
        raise ValueError(
            f"{len(protocols)} different protocols in the results; a single "
            "Table 1 cannot describe them. Re-run the odd cells or restrict "
            "--results-dir."
        )
    protocol = next(iter(protocols.values()))
    seeds = protocol.get("seeds") or []

    lines = [HEADER, r"\begin{tabular}{lr}", r"\toprule",
             r"Parameter & Value \\", r"\midrule"]
    for key, label, spec in PROTOCOL_ROWS:
        if key not in protocol:
            continue
        lines.append(f"{label} & {spec.format(float(protocol[key]))} \\\\")
    lines.append(f"Seeds & {len(seeds)} "
                 f"({', '.join(str(s) for s in seeds)}) \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def task_label(spec):
    """`env_id`, or dm_control's `domain/task`, plus the physics it was given."""
    if "env_id" in spec:
        name = spec["env_id"]
    else:
        name = f"{spec.get('domain_name')}/{spec.get('task_name')}"
    text = r"\texttt{" + latex_escape(name) + "}"
    params = spec.get("params") or {}
    parts = [label.format(params[key]) for key, label, neutral in PARAM_ROWS
             if key in params and params[key] != neutral]
    if parts:
        text += " (" + ", ".join(parts) + ")"
    return text


def d_param_of(tasks):
    """
    Eq. 8 for the pairs it is defined on, and nothing for the rest.

    `compute_d_param` differences a physics vector, so it says something only
    when the two tasks differ in physics *alone*. Where the body or the layout
    changes it would return the distance between two default vectors --- zero
    for the dm_control pairs that swap cheetah for walker --- and report a
    change of domain as no change at all. That is the gap d_trans exists to
    fill, so the cell is left empty rather than filled with a misleading 0.
    """
    task_A, task_B = tasks["task_A"], tasks["task_B"]
    identity = ("env_id", "domain_name", "task_name")
    if any(task_A.get(k) != task_B.get(k) for k in identity):
        return float("nan")
    if not (task_A.get("params") and task_B.get("params")):
        return float("nan")
    return compute_d_param(task_A["params"], task_B["params"])


def tasks_table(runs, families, distances):
    """
    The nine cells: which two environments each one trains on, in that order.

    Read from each run's `tasks` block for the same reason as the protocol —
    the levels were edited three times (F8, F25, F26) and the config is not
    evidence of what produced the numbers.
    """
    lines = [HEADER, r"\begin{tabular}{llllrr}", r"\toprule",
             r"Family & Level & Task A & Task B & $d_{\mathrm{param}}$ & "
             r"$d_{\mathrm{trans}}$ \\",
             r"\midrule"]
    previous = None
    for family in families:
        for distance in distances:
            cell = [r for r in runs if r.get("family") == family
                    and r.get("distance") == distance and r.get("tasks")]
            if not cell:
                continue
            pairs = {(task_label(r["tasks"]["task_A"]),
                      task_label(r["tasks"]["task_B"])) for r in cell}
            if len(pairs) > 1:
                raise ValueError(
                    f"{family}/{distance} was run on {len(pairs)} different "
                    "task pairs; the cell mixes environments."
                )
            task_A, task_B = next(iter(pairs))
            per_seed = [r["d_trans"] for r in cell
                        if r.get("d_trans") is not None]
            name = FAMILY_LABEL.get(family, family) if family != previous else ""
            if previous is not None and family != previous:
                lines.append(r"\addlinespace")
            previous = family
            lines.append(
                f"{name} & {LEVEL_LABEL[distance]} & {task_A} & {task_B} & "
                + fmt(d_param_of(cell[0]["tasks"]), 3) + " & "
                + (fmt(float(np.median(per_seed))) if per_seed else "--")
                + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def median_of(runs, method, family, distance, key):
    values = list(cell_values(runs, method, family, distance, key).values())
    return float(np.median(values)) if values else float("nan")


def axis_table(runs, families, distances, axis_methods, key="rd"):
    """RD per family and level, with the level it peaks at (F27)."""
    lines = [HEADER, r"\begin{tabular}{lrrrc}", r"\toprule",
             r"Family & min & med & max & Peak \\", r"\midrule"]
    for family in families:
        values = [axis_value(runs, axis_methods, family, d, key)
                  for d in distances]
        if all(np.isnan(v) for v in values):
            continue
        peak = LEVEL_LABEL[distances[int(np.nanargmax(values))]]
        cells = " & ".join(
            (r"\textbf{" + fmt(v) + "}" if LEVEL_LABEL[distances[i]] == peak
             else fmt(v))
            for i, v in enumerate(values))
        lines.append(f"{FAMILY_LABEL.get(family, family)} & {cells} & "
                     f"{peak} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def predictor_table(runs, families, distances, axis_methods, key="rd"):
    """The nine cells behind the rank correlations, and the correlations."""
    cells, observed, labels, d_trans, difficulty = [], [], [], [], []
    for family in families:
        for distance in distances:
            value = axis_value(runs, axis_methods, family, distance, key)
            if np.isnan(value):
                continue
            cells.append((family, distance))
            observed.append(value)
            labels.append(distances.index(distance))
            per_seed = [r["d_trans"] for r in runs
                        if r.get("family") == family
                        and r.get("distance") == distance
                        and r.get("d_trans") is not None]
            d_trans.append(float(np.median(per_seed)) if per_seed
                           else float("nan"))
            difficulty.append(axis_value(
                runs, axis_methods, family, distance,
                "heldout_reconstruction_B_after_task_B"))

    lines = [HEADER, r"\begin{tabular}{llrrr}", r"\toprule",
             r"Family & Level & RD & $d_{\mathrm{trans}}$ & "
             r"Task-B difficulty \\", r"\midrule"]
    previous = None
    for (family, distance), obs, dt, diff in zip(cells, observed, d_trans,
                                                 difficulty):
        name = FAMILY_LABEL.get(family, family) if family != previous else ""
        if previous is not None and family != previous:
            lines.append(r"\addlinespace")
        previous = family
        lines.append(f"{name} & {LEVEL_LABEL[distance]} & {fmt(obs)} & "
                     f"{fmt(dt)} & {fmt(diff)} \\\\")
    lines.append(r"\midrule")
    lines.append(r"\multicolumn{2}{l}{Spearman $\rho$ with RD} & "
                 + " & ".join([
                     fmt(spearman(observed, labels)),
                     fmt(spearman(observed, d_trans)),
                     fmt(spearman(observed, difficulty)),
                 ]) + r" \\")
    lines.append(r"\multicolumn{2}{l}{\quad (predictor)} & "
                 r"\emph{labelled level} & \emph{measured} & \emph{measured}"
                 r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def encoder_table(runs, methods, families, distances, threshold=0.10):
    """
    Task-A reconstruction after task B, as a factor of what it was before.

    A factor rather than the percentage the console prints: the column has to
    hold 1.00 and 753 in the same table, and "+75244.5\\%" is unreadable next
    to "+0.0\\%". They are the same quantity, factor = 1 + loss.
    """
    controls = control_cells(runs, methods, families, distances, threshold)
    header = " & ".join(METHOD_LABEL.get(m, m) for m in methods)
    lines = [HEADER,
             r"\begin{tabular}{ll" + "r" * len(methods) + "}", r"\toprule",
             f"Family & Level & {header} \\\\", r"\midrule"]
    previous = None
    for family in families:
        for distance in distances:
            losses = [task_a_loss(runs, m, family, distance) for m in methods]
            if all(np.isnan(x) for x in losses):
                continue
            name = FAMILY_LABEL.get(family, family) if family != previous else ""
            if previous is not None and family != previous:
                lines.append(r"\addlinespace")
            previous = family
            level = LEVEL_LABEL[distance]
            if (family, distance) in controls:
                level += r"$^{\dagger}$"
            cells = " & ".join(
                "--" if np.isnan(x) else
                (f"{1 + x:.2f}" if abs(x) < 10 else f"{1 + x:.0f}")
                for x in losses)
            lines.append(f"{name} & {level} & {cells} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def method_table(runs, methods, families, distances, key):
    """Median over seeds of `key`, per method and cell, marking skewed cells."""
    header = " & ".join(METHOD_LABEL.get(m, m) for m in methods)
    lines = [HEADER,
             r"\begin{tabular}{ll" + "r" * len(methods) + "}", r"\toprule",
             f"Family & Level & {header} \\\\", r"\midrule"]
    previous = None
    for family in families:
        for distance in distances:
            cells = []
            for method in methods:
                values = list(cell_values(runs, method, family, distance,
                                          key).values())
                if not values:
                    cells.append("--")
                    continue
                median = float(np.median(values))
                text = f"{median:.2f}" if abs(median) < 100 else f"{median:.0f}"
                if is_right_skewed(values):
                    text += r"$^{\ast}$"
                cells.append(text)
            if all(c == "--" for c in cells):
                continue
            name = FAMILY_LABEL.get(family, family) if family != previous else ""
            if previous is not None and family != previous:
                lines.append(r"\addlinespace")
            previous = family
            lines.append(f"{name} & {LEVEL_LABEL[distance]} & "
                         + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--results-dir", default="results", type=Path)
    parser.add_argument("--out", default=Path("../paper/tables"), type=Path)
    parser.add_argument("--methods", nargs="+", default=METHODS)
    parser.add_argument("--families", nargs="+", default=list(FAMILY_CONFIGS))
    parser.add_argument("--distances", nargs="+", default=DISTANCES)
    parser.add_argument("--axis-methods", nargs="+", default=AXIS_METHODS)
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    runs = load_runs(args.results_dir)
    if not runs:
        raise SystemExit(f"no metrics.json found under {args.results_dir}")

    present = {(r.get("method"), r.get("family"), r.get("distance"))
               for r in runs}
    methods = [m for m in args.methods if any(p[0] == m for p in present)]
    families = [f for f in args.families if any(p[1] == f for p in present)]
    distances = [d for d in args.distances if any(p[2] == d for p in present)]
    axis_methods = [m for m in args.axis_methods if m in methods]

    tables = {
        "protocol": protocol_table(runs),
        "tasks": tasks_table(runs, families, distances),
        "axis": axis_table(runs, families, distances, axis_methods),
        "predictors": predictor_table(runs, families, distances, axis_methods),
        "encoder": encoder_table(runs, methods, families, distances),
        "pf": method_table(runs, methods, families, distances, "pf"),
        "rd": method_table(runs, methods, families, distances, "rd"),
        "ft": method_table(runs, methods, families, distances, "ft"),
    }

    args.out.mkdir(parents=True, exist_ok=True)
    for name, body in tables.items():
        path = args.out / f"tab_{name}.tex"
        path.write_text(body, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
